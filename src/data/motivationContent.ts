export function getContentForCategory(category: GoalCategory): ContentEntry[] {
  return motivationContent.filter(c => c.category_tags.includes(category));
}

export function getRandomContent(category: GoalCategory): ContentEntry {
  const matched = getContentForCategory(category);
  const pool = matched.length > 0 ? matched : motivationContent;
  return pool[Math.floor(Math.random() * pool.length)];
}
